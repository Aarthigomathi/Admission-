function t(key){
  const d = LANG_STR[LANG] || LANG_STR.en;
  return (d[key] !== undefined) ? d[key] : (LANG_STR.en[key] !== undefined ? LANG_STR.en[key] : key);
}
function tt(key, vars){
  let s = t(key);
  if(vars) for(const k in vars){ s = s.split("{"+k+"}").join(vars[k]); }
  return s;
}
function setLang(l){
  if(l!==LANG){ localStorage.setItem("edu_lang", l); location.reload(); }
}
